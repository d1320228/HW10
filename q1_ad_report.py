def ad_report(impressions, clicks, target=3.0):
    if impressions == 0:  #[cite: 3]
        return (None, False)  #[cite: 3]
    if clicks == 0:  #[cite: 3]
        ctr = 0.0  #[cite: 3]
    else:  #[cite: 3]
        ctr = clicks / impressions * 100  #[cite: 3]
    passed = ctr >= target  #[cite: 3]
    return (ctr, passed)  #[cite: 3]


student_id = input("請輸入完整學號：").strip().upper()  #[cite: 1]
tail = student_id[-3:]  #[cite: 1]
a = int(student_id[-3])  #[cite: 1]
b = int(student_id[-2])  #[cite: 1]
c = int(student_id[-1])  #[cite: 1]
s = a + b + c  #[cite: 1]

ads = [
    ("搜尋廣告", 1000 + 100 * a, 30 + 5 * b),  #[cite: 3]
    ("社群廣告", 1200 + 100 * b, 24 + 4 * c),  #[cite: 3]
    ("影音廣告", 0, 0),  #[cite: 3]
]
target = 2.5 + 0.1 * c  #[cite: 3]

print(f"學號：{student_id}")  #[cite: 4]
print(f"CTR門檻：{target:.2f}%")  #[cite: 2, 4]

passed_count = 0
for name, impressions, clicks in ads:  #[cite: 3]
    ctr, passed = ad_report(impressions, clicks, target=target)  #[cite: 3]
    if passed:  #[cite: 3]
        passed_count += 1
    if ctr is None:  #[cite: 3, 4]
        ctr_text = "無曝光資料"  #[cite: 4]
    else:  #[cite: 3, 4]
        ctr_text = f"{ctr:.2f}%"  #[cite: 2, 3, 4]
    print(f"{name}：曝光={impressions}，點擊={clicks}，CTR={ctr_text}，達標={passed}")  #[cite: 3, 4]

print(f"達標廣告數：{passed_count}")  #[cite: 3, 4]

default_res = ad_report(1000, 30)  #[cite: 3]
zero_click_res = ad_report(1000, 0)  #[cite: 3]
print(f"預設門檻測試：{default_res}")  #[cite: 3, 4]
print(f"零點擊測試：{zero_click_res}")  #[cite: 3, 4]